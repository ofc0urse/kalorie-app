function slug(s: string): string {
  return normalize(s).replace(/ /g, '-');
}

function build(): Food[] {
  const out: Food[] = [];
  for (const [category, rows] of Object.entries(DATA)) {
    for (const [nameAliases, kcal, protein, fat, carbs, fiber, portions, unit] of rows) {
      const [name, ...aliases] = nameAliases.split('|');
      out.push({
        id: `builtin:${slug(name)}`,
        source: 'builtin',
        name,
        category,
        per100: { kcal, protein, fat, carbs, fiber },
        portions: (portions ?? '')
          .split(';')
          .filter(Boolean)
          .map((p) => {
            const i = p.lastIndexOf(':');
            return { label: p.slice(0, i), grams: Number(p.slice(i + 1)) };
          }),
        unit: unit === 'ml' ? 'ml' : undefined,
        ...(aliases.length ? { aliases } : {}),
      } as Food);
    }
  }
  return out;
}

